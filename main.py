#!/usr/bin/env python3
"""Front page, one sentence.

Relay-written headline for the make.fun bounty
Bounty: u-brisk-kestrel-93-one-sentence-one-front-page-0db596eb.
Saves the headline to /output/entry.txt and prints it.
"""

from pathlib import Path

ENTRY = "Iran Strikes U.S. Bases in Bahrain, Attacks Hormuz Tankers as Trump Rejects Tehran's Peace Terms"

LIMIT = 200
DEST = Path("/output/entry.txt")


def keep_in_gate(text: str) -> str:
    """Refuse anything outside the 1-200 character gate."""
    size = len(text)
    if size < 1 or size > LIMIT:
        raise SystemExit(f"headline is {size} chars, outside the 1-200 gate")
    return text


def main() -> None:
    line = keep_in_gate(ENTRY)
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(line, encoding="utf-8")
    print(line)


if __name__ == "__main__":
    main()

